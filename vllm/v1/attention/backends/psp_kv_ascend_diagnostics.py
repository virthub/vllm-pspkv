"""Opt-in, single-request FP4 versus FP8 diagnostics for Ascend bring-up.

The shadow FP8 path reconstructs the same projected K/V generated by the FP4
model. It isolates cache-format error at each attention layer without changing
the model's execution or vLLM's scheduler. The comparison is deliberately
expensive and must never be used for a serving benchmark.
"""

from dataclasses import dataclass

import torch

from vllm.v1.attention.backends.psp_kv_ascend_packed import PackedKVCache
from vllm.v1.attention.backends.psp_kv_ascend_reference import (
    decode_e4m3,
    encode_e4m3,
)


def _relative_rmse(actual: torch.Tensor, baseline: torch.Tensor) -> float:
    error = (actual.float() - baseline.float()).square().sum()
    energy = baseline.float().square().sum().clamp_min(1e-30)
    return float((error / energy).sqrt())


@dataclass(frozen=True)
class FP4LayerComparison:
    sequence_length: int
    fp4_key_rmse: float
    fp8_key_rmse: float
    fp4_value_rmse: float
    fp8_value_rmse: float
    attention_rmse: float
    fp4_key_zero_fraction: float
    fp4_value_zero_fraction: float


class FP4LayerDiagnostics:
    """Track one request's projected K/V and compare its decode layers."""

    def __init__(self, max_decode_steps: int = 2):
        if max_decode_steps < 1:
            raise ValueError("FP4 diagnostics needs at least one decode step")
        self.max_decode_steps = max_decode_steps
        self.key_history: torch.Tensor | None = None
        self.value_history: torch.Tensor | None = None
        self.decode_steps = 0

    def observe(
        self,
        query: torch.Tensor,
        key: torch.Tensor,
        value: torch.Tensor,
        fp4_output: torch.Tensor,
        cache: PackedKVCache,
        block_scales: torch.Tensor,
        block_table: torch.Tensor,
        sequence_length: int,
        attention_scale: float,
    ) -> FP4LayerComparison | None:
        num_queries = key.shape[0]
        prefix_length = sequence_length - num_queries
        if prefix_length < 0 or query.shape[0] != num_queries:
            raise ValueError("FP4 diagnostics received inconsistent query lengths")
        if prefix_length == 0:
            self.key_history = key.float().clone()
            self.value_history = value.float().clone()
            self.decode_steps = 0
            return None
        if self.key_history is None or self.value_history is None:
            raise ValueError("FP4 diagnostics must observe prefill before decode")
        if self.key_history.shape[0] != prefix_length:
            raise ValueError("FP4 diagnostics lost the request's token history")
        self.key_history = torch.cat((self.key_history, key.float()))
        self.value_history = torch.cat((self.value_history, value.float()))
        if num_queries != 1 or self.decode_steps >= self.max_decode_steps:
            return None
        self.decode_steps += 1

        num_blocks = (sequence_length + cache.block_size - 1) // cache.block_size
        physical_ids = block_table[:num_blocks].to(torch.int64)
        fp4_keys, fp4_values = cache.gather(physical_ids)
        scales = block_scales.index_select(0, physical_ids)
        if scales.ndim == 2:
            key_scales = value_scales = scales[:, None, :, None]
        else:
            group_size = cache.head_size // scales.shape[-1]
            key_scales = scales[:, 0].repeat_interleave(group_size, dim=-1)[:, None]
            value_scales = scales[:, 1].repeat_interleave(group_size, dim=-1)[:, None]
        fp4_keys = (fp4_keys * key_scales).reshape(
            -1, cache.num_kv_heads, cache.head_size
        )[:sequence_length]
        fp4_values = (fp4_values * value_scales).reshape(
            -1, cache.num_kv_heads, cache.head_size
        )[:sequence_length]
        assert self.key_history is not None and self.value_history is not None
        fp8_keys = decode_e4m3(encode_e4m3(self.key_history))
        fp8_values = decode_e4m3(encode_e4m3(self.value_history))

        groups = query.shape[1] // cache.num_kv_heads
        expanded_keys = fp8_keys.repeat_interleave(groups, dim=1)
        expanded_values = fp8_values.repeat_interleave(groups, dim=1)
        scores = (
            torch.bmm(
                query.float().transpose(0, 1),
                expanded_keys.transpose(0, 1).transpose(1, 2),
            )
            * attention_scale
        )
        fp8_output = torch.bmm(
            torch.softmax(scores, dim=-1), expanded_values.transpose(0, 1)
        ).transpose(0, 1)
        return FP4LayerComparison(
            sequence_length=sequence_length,
            fp4_key_rmse=_relative_rmse(fp4_keys, self.key_history),
            fp8_key_rmse=_relative_rmse(fp8_keys, self.key_history),
            fp4_value_rmse=_relative_rmse(fp4_values, self.value_history),
            fp8_value_rmse=_relative_rmse(fp8_values, self.value_history),
            attention_rmse=_relative_rmse(fp4_output, fp8_output),
            fp4_key_zero_fraction=float((fp4_keys == 0).float().mean()),
            fp4_value_zero_fraction=float((fp4_values == 0).float().mean()),
        )
