"""Ascend entry points matching PSP-KV's three packed attention launchers.

The CUDA BTKV reference ignores its TMA descriptors and uses the same
head-major K / transposed V byte layout as enhanced. Ascend has no CUDA TMA;
the native kernels implement the reference's observable cache contract.
"""

import os
from functools import lru_cache

import torch

from vllm.v1.attention.backends.psp_kv_ascend_native import load_native_fp8_ops

_TARGET_DTYPES = {
    torch.bfloat16: 0,
    torch.float16: 1,
    torch.float8_e4m3fn: 2,
    torch.float8_e5m2: 3,
}

_ATTENTION_IMPL = os.environ.get("PSPKV_ASCEND_ATTENTION_IMPL", "vector")


@lru_cache(maxsize=32)
def _tile_permutation(device: torch.device, dimension: int) -> torch.Tensor:
    indices = torch.arange(32 * dimension, dtype=torch.int32)
    return ((indices % dimension * 32 + indices // dimension) * 4).to(device)


@lru_cache(maxsize=32)
def _scratch_block_table(
    device: torch.device, sequences: int, blocks: int
) -> torch.Tensor:
    return torch.arange(sequences * blocks, dtype=torch.int32, device=device).view(
        sequences, blocks
    )


@lru_cache(maxsize=2)
def packed_lookup_tables(
    device: torch.device,
) -> tuple[torch.Tensor, torch.Tensor, torch.Tensor]:
    """Bit-exact decode tables generated by the Python reference codec.

    The vectorized Ascend C kernels decode cache bytes through these tables,
    so their results are identical to the scalar kernels and the reference.
    """
    from vllm.v1.attention.backends.psp_kv_ascend_reference import (
        decode_e2m1,
        decode_e4m3,
        decode_e5m2,
    )

    e4m3 = decode_e4m3(torch.arange(256, dtype=torch.uint8)).to(device)
    e5m2 = decode_e5m2(torch.arange(256, dtype=torch.uint8)).to(device)
    # Pad the 16-entry FP4 table to 256 floats so the Ascend C kernels use
    # the same UB DataCopy path as the FP8 tables (16-entry copies were not
    # reliable on 910B3).
    fp4 = torch.zeros(256, dtype=torch.float32)
    fp4[:16] = decode_e2m1(torch.arange(16, dtype=torch.uint8))
    return e4m3, e5m2, fp4.to(device)


class PSPKVAscendPackedOps:
    """Dispatch the original packed-cache attention signatures on NPU."""

    @staticmethod
    def quantize_and_scatter_kv(
        prefill_scratch: torch.Tensor,
        key_cache: torch.Tensor,
        value_cache: torch.Tensor,
        block_tables: torch.Tensor,
        slot_mapping: torch.Tensor,
        precision_table: torch.Tensor,
        block_offsets: torch.Tensor,
        scale_table: torch.Tensor,
        num_tokens: int,
        format_generation: int = 0,
        preserve_scales: bool = False,
        block_size: int = 16,
    ) -> None:
        if block_tables.dtype != torch.int32 or block_tables.ndim != 2:
            raise ValueError("PSP-KV packed scatter needs int32 block tables")
        load_native_fp8_ops().packed_scatter(
            prefill_scratch,
            key_cache,
            value_cache,
            slot_mapping,
            precision_table,
            block_offsets,
            scale_table,
            num_tokens,
            block_size,
            format_generation,
            preserve_scales,
        )

    @staticmethod
    def psp_dequantize_kv(
        key_cache: torch.Tensor,
        value_cache: torch.Tensor,
        block_offsets: torch.Tensor,
        precision_table: torch.Tensor,
        scale_table: torch.Tensor,
        num_blocks: int,
        num_kv_heads: int,
        block_size: int,
        head_size: int,
        key_out: torch.Tensor,
        value_out: torch.Tensor,
        format_generation: int = 0,
    ) -> None:
        if (
            key_out.shape != (num_blocks, num_kv_heads, block_size, head_size)
            or value_out.shape != key_out.shape
            or value_out.dtype != key_out.dtype
        ):
            raise ValueError("PSP-KV dequant output shape or dtype mismatch")
        ops = load_native_fp8_ops()
        key_float, value_float = ops.packed_dequant(
            key_cache,
            value_cache,
            block_offsets,
            precision_table,
            scale_table,
            block_size,
            head_size,
            _TARGET_DTYPES[key_out.dtype],
            format_generation,
        )
        if key_out.dtype in (torch.float8_e4m3fn, torch.float8_e5m2):
            ops.cast_fp8_output(key_float, key_out)
            ops.cast_fp8_output(value_float, value_out)
        else:
            key_out.copy_(key_float.to(key_out.dtype))
            value_out.copy_(value_float.to(value_out.dtype))

    @staticmethod
    def psp_attention_uniform(
        query: torch.Tensor,
        key_cache: torch.Tensor,
        value_cache: torch.Tensor,
        block_tables: torch.Tensor,
        context_lens: torch.Tensor,
        softmax_scale: float,
        num_kv_heads: int,
        head_size: int,
        out: torch.Tensor,
    ) -> None:
        if (
            query.ndim != 3
            or out.shape != query.shape
            or key_cache.shape != value_cache.shape
            or key_cache.ndim != 4
            or key_cache.shape[1] != num_kv_heads
            or key_cache.shape[3] != head_size
            or key_cache.dtype != query.dtype
            or value_cache.dtype != query.dtype
            or out.dtype != query.dtype
        ):
            raise ValueError("PSP-KV uniform attention shape or dtype mismatch")
        ops = load_native_fp8_ops()
        scores = ops.uniform_scores(
            query, key_cache, block_tables, context_lens, softmax_scale
        )
        probabilities = torch.softmax(scores, dim=-1)
        result = ops.uniform_weighted_value(
            probabilities,
            value_cache,
            block_tables,
            context_lens,
            _TARGET_DTYPES[query.dtype],
        )
        if query.dtype in (torch.float8_e4m3fn, torch.float8_e5m2):
            ops.cast_fp8_output(result, out)
        else:
            out.copy_(result.to(query.dtype))

    @staticmethod
    def _attention(
        generation: int,
        query: torch.Tensor,
        key_cache: torch.Tensor,
        value_cache: torch.Tensor,
        block_tables: torch.Tensor,
        context_lens: torch.Tensor,
        precision_table: torch.Tensor,
        block_offsets: torch.Tensor,
        scale_table: torch.Tensor | None,
        softmax_scale: float,
        num_kv_heads: int,
        head_size: int,
        out: torch.Tensor,
        block_size: int = 16,
        context_lens_cpu: torch.Tensor | None = None,
    ) -> None:
        if query.dtype not in _TARGET_DTYPES or out.dtype != query.dtype:
            raise ValueError("PSP-KV packed attention needs matching FP16/BF16/FP8 Q/O")
        if query.ndim != 3 or query.shape[2] != head_size or out.shape != query.shape:
            raise ValueError("PSP-KV packed query/output shape mismatch")
        if key_cache.dtype != torch.uint8 or value_cache.dtype != torch.uint8:
            raise ValueError("PSP-KV packed caches must be byte arenas")
        if scale_table is None:
            if generation != 0:
                raise ValueError("Enhanced/BTKV need a per-head scale table")
            scale_table = torch.empty(0, device=query.device, dtype=torch.float32)
        ops = load_native_fp8_ops()
        if context_lens_cpu is not None:
            if (
                query.dtype != torch.bfloat16
                or generation not in (0, 1, 2)
                or head_size not in (128, 256)
                or block_size != 128
                or context_lens_cpu.device.type != "cpu"
                or context_lens_cpu.dtype != torch.int32
                or context_lens_cpu.shape != context_lens.shape
                or not context_lens_cpu.is_contiguous()
            ):
                raise ValueError(
                    "Native paged scratch needs BF16, 128-token pages "
                    "and CPU int32 lengths"
                )
            import torch_npu

            # Only active pages are materialized; there is no persistent BF16
            # copy of the compressed arena. The original layouts stay intact.
            gather = ops.gather_paged_bf16
            table_args = []
            if _ATTENTION_IMPL != "gather" and hasattr(ops, "gather_paged_bf16_vec"):
                gather = ops.gather_paged_bf16_vec
                e4, e5, _ = packed_lookup_tables(query.device)
                table_args = [e4, e5, _tile_permutation(query.device, head_size)]
            key, value = gather(
                key_cache,
                value_cache,
                block_tables,
                context_lens,
                precision_table,
                block_offsets,
                scale_table,
                *table_args,
                generation,
                num_kv_heads,
                head_size,
                block_size,
            )
            torch_npu._npu_paged_attention(
                query=query,
                key_cache=key,
                value_cache=value,
                num_kv_heads=num_kv_heads,
                num_heads=query.shape[1],
                scale_value=softmax_scale,
                block_table=_scratch_block_table(
                    query.device, query.shape[0], block_tables.shape[1]
                ),
                context_lens=context_lens_cpu,
                out=out,
            )
            return
        scores = ops.packed_scores(
            query,
            key_cache,
            block_tables,
            context_lens,
            precision_table,
            block_offsets,
            scale_table,
            generation,
            num_kv_heads,
            block_size,
            softmax_scale,
        )
        probabilities = torch.softmax(scores, dim=-1)
        result = ops.packed_weighted_value(
            probabilities,
            value_cache,
            block_tables,
            context_lens,
            precision_table,
            block_offsets,
            scale_table,
            generation,
            num_kv_heads,
            head_size,
            block_size,
            _TARGET_DTYPES[query.dtype],
        )
        if query.dtype in (torch.float8_e4m3fn, torch.float8_e5m2):
            ops.cast_fp8_output(result, out)
        else:
            out.copy_(result.to(query.dtype))

    def psp_attention_basic(
        self,
        query: torch.Tensor,
        key_cache: torch.Tensor,
        value_cache: torch.Tensor,
        block_tables: torch.Tensor,
        context_lens: torch.Tensor,
        precision_table: torch.Tensor,
        block_offsets: torch.Tensor,
        softmax_scale: float,
        num_kv_heads: int,
        head_size: int,
        out: torch.Tensor,
        *,
        context_lens_cpu: torch.Tensor | None = None,
        block_size: int = 16,
    ) -> None:
        self._attention(
            0,
            query,
            key_cache,
            value_cache,
            block_tables,
            context_lens,
            precision_table,
            block_offsets,
            None,
            softmax_scale,
            num_kv_heads,
            head_size,
            out,
            block_size=block_size,
            context_lens_cpu=context_lens_cpu,
        )

    def psp_attention_scaled_basic(
        self,
        query: torch.Tensor,
        key_cache: torch.Tensor,
        value_cache: torch.Tensor,
        block_tables: torch.Tensor,
        context_lens: torch.Tensor,
        precision_table: torch.Tensor,
        block_offsets: torch.Tensor,
        scale_table: torch.Tensor,
        softmax_scale: float,
        num_kv_heads: int,
        head_size: int,
        out: torch.Tensor,
        block_size: int = 16,
    ) -> None:
        """Token-major V with per-head scales for the live uniform FP4 cache."""
        self._attention(
            3,
            query,
            key_cache,
            value_cache,
            block_tables,
            context_lens,
            precision_table,
            block_offsets,
            scale_table,
            softmax_scale,
            num_kv_heads,
            head_size,
            out,
            block_size,
        )

    def psp_attention_scaled_basic_vec(
        self,
        query: torch.Tensor,
        key_cache: torch.Tensor,
        value_cache: torch.Tensor,
        block_tables: torch.Tensor,
        context_lens: torch.Tensor,
        precision_table: torch.Tensor,
        block_offsets: torch.Tensor,
        scale_table: torch.Tensor,
        softmax_scale: float,
        num_kv_heads: int,
        head_size: int,
        out: torch.Tensor,
        block_size: int = 16,
        value_precision_table: torch.Tensor | None = None,
        value_block_offsets: torch.Tensor | None = None,
    ) -> None:
        """Scaled-basic attention through the UB-staged vectorized kernels.

        Same contract and bit-identical results as ``_attention(3, ...)``;
        the decode bytes are read through Python-generated lookup tables so
        the arithmetic order matches the scalar kernels exactly. Optional
        value tables let K and V use different precision plans and byte
        offsets.
        """
        if query.dtype not in _TARGET_DTYPES or out.dtype != query.dtype:
            raise ValueError("PSP-KV packed attention needs matching FP16/BF16/FP8 Q/O")
        if query.ndim != 3 or query.shape[2] != head_size or out.shape != query.shape:
            raise ValueError("PSP-KV packed query/output shape mismatch")
        if key_cache.dtype != torch.uint8 or value_cache.dtype != torch.uint8:
            raise ValueError("PSP-KV packed caches must be byte arenas")
        if scale_table is None or scale_table.dtype != torch.float32:
            raise ValueError("Scaled-basic vec attention needs a float32 scale table")
        ops = load_native_fp8_ops()
        e4m3_table, e5m2_table, fp4_table = packed_lookup_tables(query.device)
        scores = ops.packed_scores_vec(
            query,
            key_cache,
            block_tables,
            context_lens,
            precision_table,
            block_offsets,
            scale_table,
            e4m3_table,
            e5m2_table,
            fp4_table,
            3,
            num_kv_heads,
            block_size,
            softmax_scale,
        )
        probabilities = torch.softmax(scores, dim=-1)
        result = ops.packed_weighted_value_vec(
            probabilities,
            value_cache,
            block_tables,
            context_lens,
            value_precision_table
            if value_precision_table is not None
            else precision_table,
            value_block_offsets if value_block_offsets is not None else block_offsets,
            scale_table,
            e4m3_table,
            e5m2_table,
            fp4_table,
            3,
            num_kv_heads,
            head_size,
            block_size,
            _TARGET_DTYPES[query.dtype],
        )
        out.copy_(result.to(query.dtype))

    def psp_attention_scaled_basic_fused(
        self,
        query: torch.Tensor,
        key_cache: torch.Tensor,
        value_cache: torch.Tensor,
        block_tables: torch.Tensor,
        context_lens: torch.Tensor,
        precision_table: torch.Tensor,
        block_offsets: torch.Tensor,
        scale_table: torch.Tensor,
        softmax_scale: float,
        num_kv_heads: int,
        head_size: int,
        out: torch.Tensor,
        block_size: int = 16,
    ) -> None:
        """Single-kernel compressed-KV QK, softmax, and weighted V decode."""
        if query.dtype not in _TARGET_DTYPES or out.dtype != query.dtype:
            raise ValueError("PSP-KV fused decode needs matching FP16/BF16/FP8 Q/O")
        if query.ndim != 3 or query.shape[2] != head_size or out.shape != query.shape:
            raise ValueError("PSP-KV fused query/output shape mismatch")
        if key_cache.dtype != torch.uint8 or value_cache.dtype != torch.uint8:
            raise ValueError("PSP-KV fused caches must be byte arenas")
        ops = load_native_fp8_ops()
        if not hasattr(ops, "packed_fused_decode"):
            raise RuntimeError(
                "PSP-KV fused decode requires the rebuilt native library"
            )
        result = ops.packed_fused_decode(
            query.contiguous(),
            key_cache,
            value_cache,
            block_tables.contiguous(),
            context_lens.contiguous(),
            precision_table,
            block_offsets,
            scale_table,
            num_kv_heads,
            block_size,
            softmax_scale,
        )
        out.copy_(result.to(query.dtype))

    def psp_attention_enhanced(
        self,
        query: torch.Tensor,
        key_cache: torch.Tensor,
        value_cache: torch.Tensor,
        block_tables: torch.Tensor,
        context_lens: torch.Tensor,
        precision_table: torch.Tensor,
        block_offsets: torch.Tensor,
        scale_table: torch.Tensor,
        softmax_scale: float,
        num_kv_heads: int,
        head_size: int,
        out: torch.Tensor,
        *,
        context_lens_cpu: torch.Tensor | None = None,
        block_size: int = 16,
    ) -> None:
        self._attention(
            1,
            query,
            key_cache,
            value_cache,
            block_tables,
            context_lens,
            precision_table,
            block_offsets,
            scale_table,
            softmax_scale,
            num_kv_heads,
            head_size,
            out,
            block_size=block_size,
            context_lens_cpu=context_lens_cpu,
        )

    def psp_attention_btkv(
        self,
        query: torch.Tensor,
        key_cache: torch.Tensor,
        value_cache: torch.Tensor,
        block_tables: torch.Tensor,
        context_lens: torch.Tensor,
        precision_table: torch.Tensor,
        block_offsets: torch.Tensor,
        scale_table: torch.Tensor,
        tma_descriptors: torch.Tensor,
        softmax_scale: float,
        num_kv_heads: int,
        head_size: int,
        out: torch.Tensor,
        *,
        context_lens_cpu: torch.Tensor | None = None,
        block_size: int = 16,
    ) -> None:
        if (
            tma_descriptors.dtype != torch.int64
            or tma_descriptors.ndim != 2
            or tma_descriptors.shape[0] != precision_table.numel()
            or tma_descriptors.stride(0) * tma_descriptors.element_size() % 64
        ):
            raise ValueError("PSP-KV BTKV descriptor shape/alignment mismatch")
        self._attention(
            2,
            query,
            key_cache,
            value_cache,
            block_tables,
            context_lens,
            precision_table,
            block_offsets,
            scale_table,
            softmax_scale,
            num_kv_heads,
            head_size,
            out,
            block_size=block_size,
            context_lens_cpu=context_lens_cpu,
        )
